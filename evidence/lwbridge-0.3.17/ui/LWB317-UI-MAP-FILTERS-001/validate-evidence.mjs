import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url)),repo=path.resolve(here,'../../../..');
const read=name=>JSON.parse(fs.readFileSync(path.join(here,name),'utf8'));
const hash=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
const manifest=read('manifest.json');
for(const entry of [...manifest.files,...manifest.images,...manifest.protectedWip]){
  const bytes=fs.readFileSync(path.join(repo,entry.path));assert.equal(hash(bytes),entry.sha256,entry.path);assert.equal(bytes.length,entry.bytes,entry.path);
}
assert.equal(hash(fs.readFileSync(manifest.target.path)),manifest.target.sha256);
const staged=execFileSync('git',['diff','--cached','--name-only'],{cwd:repo,encoding:'utf8'}).split(/\r?\n/);
for(const entry of manifest.protectedWip)assert.ok(!staged.includes(entry.path),'Protected WIP must remain unstaged');
const filters=read('filter-results.json');assert.equal(filters.currentResults.comparisons,472);assert.deepEqual(filters.currentResults.failures,[]);assert.equal(filters.baseline.failures.length,330);
const treasure=read('treasure-results.json');assert.equal(treasure.comparisons,216);assert.equal(treasure.fenceCases,384);assert.equal(treasure.producerResults.length,8);assert.equal(treasure.frontend.treasureMethodsExposed,false);
const source=read('source-contract.json');assert.equal(source.evidenceState,'EXACT_BYTES');
const browser=read('browser-results.json');assert.equal(browser.flows.length,15);assert.deepEqual(browser.consoleErrors,[]);
const find=name=>{const item=browser.flows.find(item=>item.case===name);assert.ok(item,name);return item;};
const values=item=>Object.fromEntries(item.view.filters.map(field=>[field.label,field.value]));
assert.deepEqual(values(find('Train starts with independent defaults')),{Quality:'',Item:''});
assert.deepEqual(values(find('Truck choices restored after Train edits')),{Quality:'ssr',Item:'fixture-reward'});
assert.deepEqual(values(find('Train choice and item-count sort survive Truck clear')),{Quality:'ur',Item:'fixture-supply'});
assert.ok(find('Train choice and item-count sort survive Truck clear').view.headers.includes('Items1'));
assert.ok(find('Truck item clear removes only Truck item-count sort').view.headers.includes('Items'));
assert.ok(!find('Truck item clear removes only Truck item-count sort').view.headers.includes('Items1'));
const level=find('Secret Task exact level 6');assert.equal(level.allLevelValues.length,15);assert.ok(level.allLevelValues.every(value=>value==='6'));
assert.deepEqual(values(find('Ghost Ops starts with independent defaults')),{Status:'',Quality:''});
assert.deepEqual(values(find('Secret Task filters restored after Ghost edits')),{Status:'pending',Level:'6',Quality:'special'});
const english=find('Treasure Checking English preview').view.rows;
assert.deepEqual(english[0].slice(3,5),['Checking','Checking']);assert.deepEqual(english[1].slice(3,5),['Claimable','Claimed']);assert.deepEqual(english[2].slice(3,5),['Checking','Other alliance']);
assert.deepEqual(find('Treasure Checking Japanese preview').view.rows[0].slice(3,5),['確認中','確認中']);
assert.ok(!find('Ordinary Treasure preview stays outside Checking fixture').view.rows.some(row=>row.includes('Checking')));
assert.ok(browser.flows.every(item=>item.view.loading==='false'&&item.view.nativeButtonsDisabled));
const currentBuild=JSON.parse(fs.readFileSync(path.join(repo,'src/LWBridge.UI-0.3.17/dist/lwbridge-ui-build.json')));
assert.deepEqual(currentBuild,manifest.build);
const verification=read('verification.json');assert.ok(verification.checks.every(check=>check.exitCode===0));
console.log('LWB317_MAP_FILTER_EVIDENCE_OK source/code/baseline/browser/images/package/protected WIP');
