import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const {chromium}=createRequire('C:/Users/chimw/AppData/Local/Temp/lwbridge-playwright/package.json')('playwright');
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const issues=[];
try {
 const context=await browser.newContext({viewport:{width:1280,height:900}});
 const page=await context.newPage();
 page.on('console',m=>{if(['warning','error'].includes(m.type()))issues.push(m.text());});
 page.on('pageerror',e=>issues.push(e.message));
 await page.goto(`http://127.0.0.1:${Number(process.argv[2]||4410)}/?previewPage=automation&previewState=automation-positive&previewLanguage=en&previewTheme=light`);
 await page.locator('.automation-categories button').nth(1).click();
 const card=page.locator('.automation-card:visible').filter({has:page.locator('h3', {hasText:'Automatic Alliance Train Boarding'})});
 await card.waitFor();
 const expand=card.locator('.automation-config-trigger');
 if(await expand.getAttribute('aria-expanded')==='false')await expand.click();
 const choices=card.locator('.automation-preference-item input[type=checkbox]');
 for(let index=0;index<2;index++)if(!await choices.nth(index).isChecked())await choices.nth(index).check();
 const selected=card.locator('.automation-preference-item.selected');
 assert.ok(await selected.count()>=2);
 await selected.nth(0).evaluate(element=>element.dispatchEvent(new DragEvent('dragstart',{bubbles:true,cancelable:true,dataTransfer:new DataTransfer()})));
 await page.waitForFunction(()=>document.querySelector('.automation-preference-item.dragging'));
 await selected.nth(1).evaluate(element=>element.dispatchEvent(new DragEvent('dragover',{bubbles:true,cancelable:true,dataTransfer:new DataTransfer()})));
 const classes=await selected.evaluateAll(elements=>elements.map(element=>element.className));
 const actualDragOver=await card.locator('.automation-preference-item.drag-over').count();
 assert.equal(actualDragOver,0,'Pinned current counterexample: drag target does not acquire recovered drag-over class');
 await page.screenshot({path:path.join(here,'train-drag-current.png'),fullPage:true});
 await selected.nth(0).evaluate(element=>element.dispatchEvent(new DragEvent('dragend',{bubbles:true,cancelable:true,dataTransfer:new DataTransfer()})));
 await card.locator('input[name=preview-train-mode]').nth(1).check();
 await card.locator('input[name=preview-vip-train-mode]').nth(1).check();
 const fixedSelections=await card.locator('.automation-carriage-choices').evaluateAll(groups=>groups.map(group=>[...group.querySelectorAll('input')].slice(1).map((input,index)=>input.checked?index+1:null).filter(Boolean)));
 assert.deepEqual(issues,[]);
 const result={status:'COUNTEREXAMPLE_REPRODUCED',proof:'Actual mounted production local drag handlers with DOM DragEvents; physical HTML5 drag is not claimed',classes,actualDragOver,expectedRecoveredDragOver:1,fixedSelections,seedNote:'Observed fixture values only; differing input alone is not classified as a defect',consoleIssues:issues};
 fs.writeFileSync(path.join(here,'train-browser-results.json'),JSON.stringify(result,null,2)+'\n');
 console.log(JSON.stringify(result));
} finally {await browser.close();}
