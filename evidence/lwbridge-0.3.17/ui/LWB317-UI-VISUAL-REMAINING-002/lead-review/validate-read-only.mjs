import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const repo=path.resolve(here,'../../../../..');
const read=name=>fs.readFileSync(path.join(here,name));
const sha=bytes=>crypto.createHash('sha256').update(bytes).digest('hex').toUpperCase();
const app=JSON.parse(read('full-app-current-results.json'));
assert.equal(Object.keys(app.sourceFiles).length,67);
for(const [relative,expected] of Object.entries(app.sourceFiles))assert.equal(sha(fs.readFileSync(path.join(repo,relative))),expected,relative);
assert.equal(app.assertions.length,213);
assert.equal(app.screenshots.length,11);
assert.deepEqual(app.consoleIssues,[]);
for(const screenshot of app.screenshots){
 const bytes=read(`browser-current/${screenshot.file}`);
 assert.equal(sha(bytes),screenshot.sha256,screenshot.file);
 assert.equal(bytes.length,screenshot.bytes);
 assert.equal(bytes.subarray(0,8).toString('hex'),'89504e470d0a1a0a');
}
const shell=read('shell-callback-results.jsonl').toString('utf8').trim().split(/\r?\n/).map(line=>JSON.parse(line));
